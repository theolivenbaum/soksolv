package main

// exp-489 known-path diagnosis (diagnostics only; off unless -strategy pathdiag):
//
//	soksolv -strategy pathdiag -nodes N -pd-sol FILE.lurd -pd-lane macro|novelty|festbfwd|pull|hubpull [-pd-frac F] [-pd-out OUT.jsonl] LEVEL.xsb INDEX
//
// exp-731: pull and hubpull are the backward twins. The solution is reversed (pdReverse: the goal board first, each
// macro undone as one pull macro) and walked through the pull lane's open() (pull: -strategy pull's solver; hubpull:
// hub-pull's Festival-ordered pull solver, pfOn with festXStyle, its pf-* filters on), from the root whose player zone
// holds the solution's final player.
//
// Phase A (replay) walks the solution's macro sequence (maximal runs of consecutive pushes of one box) through the
// chosen lane's real move generation from the root: at each step it records whether the macro is generated, which
// pruning rule removes it if not (pdWatch hooks in open and the apply-time provers), its rank/weight among siblings,
// the advisors that picked it and the first score feature that separates it from the best sibling.
// Phase B (bounded run) runs the lane for N expansions on a fresh solver and records when each path state is first
// generated and expanded. The divergence point is the first path state the bounded run never stored; the cause class
// combines both phases (see pdClassify).
//
// festbfwd is our toward search (the festb forward half) aimed at the path state at fraction -pd-frac of the
// solution (an oracle hub; 1 = the goal board).

